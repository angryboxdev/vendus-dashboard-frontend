/** Fila offline em memória (testes). */
export function memoryQueue(): PunchQueueStoragePort & { items: QueuedPunch[] } {
  const q = {
    items: [] as QueuedPunch[],
    load: () => [...q.items],
    save: (items: QueuedPunch[]) => {
      q.items = [...items];
    },
  };
  return q;
}

